"""
Contract-driven Request Compiler Unit Tests (FIX 4, FIX 5, FIX 12, FIX 20)

Verifies the outgoing HTTP request representation generated by RequestCompiler
for various Spring MVC endpoint contracts without calling live Java endpoints.
"""
import pytest
from app.planes.knowledge.tool_registry import ToolRegistryEntry
from app.planes.execution.request_compiler import RequestCompiler, serialize_wire_value


def test_request_compiler_headers_and_path():
    tool = ToolRegistryEntry(
        tool_id="ticket_resolve_post",
        name="resolveTicket",
        description="Resolve support ticket",
        domain="SUPPORT",
        module="Ticket",
        capability="ticket.resolve",
        endpoint="/api/tickets/{ticketId}/resolve",
        http_method="POST",
        request_schema=[{"name": "resolutionNotes", "java_type": "String"}],
        response_schema=None,
        required_parameters=[{"name": "ticketId", "location": "path", "java_type": "String", "required": True}],
        optional_parameters=[],
        header_parameters=[{"name": "employeeId", "location": "header", "java_type": "String", "required": True}],
        auth_required=True,
    )

    args = {"ticketId": "TCK_123", "employeeId": "EMP_55", "resolutionNotes": "Fixed network cable"}
    compiled = RequestCompiler.compile(tool, args, bearer_token="secret_jwt_token")

    assert compiled.method == "POST"
    assert compiled.url_path == "/api/tickets/TCK_123/resolve"
    assert compiled.headers.get("Authorization") == "Bearer secret_jwt_token"
    assert compiled.headers.get("employeeId") == "EMP_55"
    assert compiled.headers.get("Accept") == "application/json"
    assert compiled.json_body == {"resolutionNotes": "Fixed network cable"}


def test_request_compiler_multipart_file_and_scalar():
    tool = ToolRegistryEntry(
        tool_id="claim_submit_post",
        name="submitClaim",
        description="Submit claim with receipt",
        domain="EXPENSE",
        module="Claim",
        capability="claim.submit",
        endpoint="/api/v1/claims/submit",
        http_method="POST",
        request_schema=[],
        response_schema=None,
        required_parameters=[],
        optional_parameters=[],
        has_file_upload=True,
        multipart_parts=[
            {"name": "claimType", "part_type": "scalar", "content_type": "text/plain", "required": True},
            {"name": "amount", "part_type": "scalar", "content_type": "text/plain", "required": True},
            {"name": "receipt", "part_type": "file", "content_type": "application/octet-stream", "required": True},
        ],
        auth_required=True,
    )

    args = {"claimType": "TRAVEL", "amount": 250.75}
    files = {"receipt": ("receipt.png", b"fake_png_data", "image/png")}
    compiled = RequestCompiler.compile(tool, args, bearer_token="jwt_99", file_inputs=files)

    assert compiled.method == "POST"
    assert compiled.url_path == "/api/v1/claims/submit"
    assert compiled.files is not None
    part_names = [f[0] for f in compiled.files]
    assert "claimType" in part_names
    assert "amount" in part_names
    assert "receipt" in part_names


def test_date_wire_format_conversions():
    # Test standard ISO date
    assert serialize_wire_value("2026-08-15", java_type="LocalDate") == "2026-08-15"

    # Test custom DD-MM-YYYY format
    assert serialize_wire_value("2026-08-15", java_type="LocalDate", wire_format="DD-MM-YYYY") == "15-08-2026"
    assert serialize_wire_value("2026-12-31", java_type="LocalDate", wire_format="DD-MM-YYYY") == "31-12-2026"
